// Letters of each language's script, to spot AI text written in the wrong language.
const DEVANAGARI = /[ऀ-ॿ]/;
const ARABIC = /[؀-ۿ]/;
const BENGALI = /[ঀ-৿]/;
const SCRIPT: Partial<Record<LangCode, RegExp>> = {
  hi: DEVANAGARI, mr: DEVANAGARI, ne: DEVANAGARI, sa: DEVANAGARI, mai: DEVANAGARI, doi: DEVANAGARI, brx: DEVANAGARI, kok: DEVANAGARI,
  bn: BENGALI, as: BENGALI,
  pa: /[਀-੿]/, gu: /[઀-૿]/, or: /[଀-୿]/, ta: /[஀-௿]/,
  te: /[ఀ-౿]/, kn: /[ಀ-೿]/, ml: /[ഀ-ൿ]/,
  ur: ARABIC, ks: ARABIC, sd: ARABIC,
};
const INDIAN_SCRIPTS = /[؀-ۿऀ-෿]/;

/** False when the text is clearly in another language than `lang` (e.g. English after switching to Hindi). */
export function looksLikeLang(text: string, lang: LangCode): boolean {
  if (lang === "en") return !INDIAN_SCRIPTS.test(text);
  const script = SCRIPT[lang];
  return script ? script.test(text) : true;
}

export function langName(code: LangCode): string {
  return LANGUAGES.find((l) => l.code === code)?.english ?? "English";
}

/** Language name for the AI prompt (with the script where needed). */
export function aiLanguageName(code: LangCode): string {
  return AI_LANGUAGE[code] ?? langName(code);
}

export function isLang(x: unknown): x is LangCode {
  return typeof x === "string" && LANGUAGES.some((l) => l.code === x);
}
